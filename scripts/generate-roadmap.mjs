// docs/images/roadmap.svg from docs/ROADMAP.md, parity/items.json and the
// board snapshot. Never edit the picture by hand. `--stdout` prints instead
// of writing, which is how `npm run check` tests freshness.
import { writeFileSync } from 'node:fs';
import { slices, items, board, sliceStatus, path } from './lib/data.mjs';
import { STYLE, esc, wrap } from './lib/svg.mjs';

export function roadmapSvg() {
  const all = slices();
  const st = sliceStatus(all, items(), board());
  const delivered = all.filter((s) => st[s.id].state === 'done').length;
  const W = 1200, cols = 4, cw = 268, ch = 212, gx = 16, gy = 16, x0 = 40, y0 = 196;
  const rows = Math.ceil(all.length / cols);
  const H = y0 + rows * ch + (rows - 1) * gy + 68;
  const label = { done: ['DONE', 'done', '✓ delivered'], now: ['NOW', 'now', '◐ in progress'], later: ['LATER', 'todo', '○ to do'] };
  const desc = all.map((s) => `${s.id} ${s.name}: ${st[s.id].state}, reward: ${s.reward}, ${st[s.id].done} of ${st[s.id].total} items done.`).join(' ');

  const cards = all.map((s, i) => {
    const x = x0 + (i % cols) * (cw + gx), y = y0 + Math.floor(i / cols) * (ch + gy);
    const { state, done, total, task } = st[s.id];
    const [tag, cls, foot] = label[state];
    const reward = wrap(s.reward, 26).slice(0, 2);
    const frac = total ? done / total : 0;
    const crit = task?.criteria ? ` · ${task.criteria.met} of ${task.criteria.total} criteria met` : '';
    return `<g data-slice="${s.id}">
<rect x="${x}" y="${y}" width="${cw}" height="${ch}" rx="12" class="card${state === 'now' ? ' on' : ''}"/>
<text x="${x + 20}" y="${y + 32}" font-size="13" font-weight="700" letter-spacing="1.5" class="muted">${s.id}${s.journeys.length ? ' · ' + esc(s.journeys.join(' ')) : ''}</text>
<text x="${x + cw - 20}" y="${y + 32}" font-size="13" font-weight="700" letter-spacing="1.5" text-anchor="end" class="${cls}">${tag}</text>
<text x="${x + 20}" y="${y + 66}" font-size="23" font-weight="600">${esc(s.name)}</text>
<path d="M${x + 20} ${y + 86}H${x + cw - 20}" class="rule"/>
${reward.map((l, k) => `<text x="${x + 20}" y="${y + 116 + k * 22}" font-size="16">${esc(l)}</text>`).join('\n')}
<rect x="${x + 20}" y="${y + 150}" width="${cw - 40}" height="5" rx="2.5" class="track"/>
<rect x="${x + 20}" y="${y + 150}" width="${(cw - 40) * frac}" height="5" rx="2.5" class="bar"/>${state === 'now' ? `
<rect x="${x + 20}" y="${y + 150}" width="${cw - 40}" height="5" rx="2.5" fill="url(#shimmer)"/>` : ''}
<text x="${x + 20}" y="${y + 170}" font-size="13" class="muted">${done} of ${total} items done${crit}</text>
<text x="${x + 20}" y="${y + 196}" font-size="15" class="${cls}">${foot}</text>
</g>`;
  }).join('\n');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t d">
<title id="t">BarkBot roadmap</title>
<desc id="d">${delivered} of ${all.length} slices delivered. ${esc(desc)}</desc>
${STYLE}
<defs><linearGradient id="shimmer" gradientUnits="userSpaceOnUse" x1="-120" y1="0" x2="0" y2="0"><stop offset="0" stop-color="#c27a12" stop-opacity="0"/><stop offset=".5" stop-color="#efb453" stop-opacity=".55"/><stop offset="1" stop-color="#c27a12" stop-opacity="0"/><animateTransform attributeName="gradientTransform" type="translate" values="20 0;480 0" dur="3.4s" calcMode="spline" keyTimes="0;1" keySplines=".4 0 .2 1" repeatCount="indefinite"/></linearGradient></defs>
<rect class="bg" width="${W}" height="${H}" rx="16"/>
<text x="40" y="70" font-size="36" font-weight="700" letter-spacing="-0.8">BarkBot</text>
<text x="40" y="102" font-size="19" class="muted">An agent with its own computer, built slice by slice against a live oracle.</text>
<text x="1160" y="70" font-size="40" font-weight="700" text-anchor="end">${delivered}<tspan class="muted" font-weight="400"> / ${all.length}</tspan></text>
<text x="1160" y="102" font-size="16" text-anchor="end" class="muted">slices delivered</text>
<rect x="40" y="124" width="1120" height="8" rx="4" class="track"/>
<rect x="40" y="124" width="${(1120 * delivered) / all.length}" height="8" rx="4" class="bar"/>
<text x="40" y="168" font-size="16"><tspan class="done">✓ delivered</tspan><tspan class="now" dx="24">◐ in progress</tspan><tspan class="todo" dx="24">○ to do</tspan></text>
<text x="1160" y="168" font-size="16" text-anchor="end" class="muted">every slice runs real Barkpark and real claude</text>
${cards}
<text x="40" y="${H - 30}" font-size="14" class="muted">Generated by scripts/generate-roadmap.mjs from docs/ROADMAP.md, parity/items.json and the Barkpark board</text>
</svg>
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const svg = roadmapSvg();
  if (process.argv.includes('--stdout')) process.stdout.write(svg);
  else writeFileSync(path('docs', 'images', 'roadmap.svg'), svg);
}
