// docs/images/journeys.svg and docs/PARITY.md from parity/items.json and
// JOURNEYS.md. Never edit either output by hand. `--stdout` prints the
// SVG, `--md` prints the Markdown; `npm run check` uses both for freshness.
import { writeFileSync } from 'node:fs';
import { items, journeys, slices, journeyStatus, path } from './lib/data.mjs';
import { STYLE, esc, wrap } from './lib/svg.mjs';

const STATE = {
  done: ['BUILT', 'done', '✓'],
  partial: ['PARTIAL', 'now', '◐'],
  open: ['OPEN', 'todo', '○'],
  unknown: ['UNREAD', 'unk', '?'],
};
const ITEM = { done: 'done', partial: 'now', open: 'todo', unknown: 'unk' };

function counts(its) {
  const c = { done: 0, partial: 0, open: 0, unknown: 0 };
  for (const i of its) c[i.status]++;
  return c;
}

export function journeysSvg() {
  const its = items(), js = journeys(), c = counts(its);
  const W = 1200, cols = 5, tw = 211.2, th = 168, g = 16, x0 = 40, y0 = 214;
  const rows = Math.ceil(js.length / cols), H = y0 + rows * th + (rows - 1) * g + 64;
  const total = its.length;
  let bx = 40;
  const seg = ['done', 'partial', 'open', 'unknown'].map((k) => {
    const w = (1120 * c[k]) / total;
    const r = w ? `<rect x="${bx}" y="124" width="${w}" height="8" class="${ITEM[k]}"/>` : '';
    bx += w;
    return r;
  }).join('');

  const tiles = js.map((j, n) => {
    const x = x0 + (n % cols) * (tw + g), y = y0 + Math.floor(n / cols) * (th + g);
    const s = journeyStatus(j, its);
    const [tag, cls] = STATE[s.state];
    const lines = wrap(j.text.replace(/\.$/, ''), 25).slice(0, 4);
    if (wrap(j.text, 25).length > 4) lines[3] = lines[3].replace(/\s*\S*$/, ' …');
    const mine = its.filter((i) => i.journey === j.id);
    const dots = mine.map((i, k) => `<circle cx="${x + 26 + k * 14}" cy="${y + th - 22}" r="5" class="${ITEM[i.status]}"/>`).join('');
    return `<g data-journey="${j.id}">
<rect x="${x}" y="${y}" width="${tw}" height="${th}" rx="12" class="card"/>
<text x="${x + 18}" y="${y + 30}" font-size="15" font-weight="700">${j.id}<tspan class="muted" font-weight="400" dx="8">${j.slice}</tspan></text>
<text x="${x + tw - 18}" y="${y + 30}" font-size="12" font-weight="700" letter-spacing="1.2" text-anchor="end" class="${cls}">${tag}</text>
${lines.map((l, k) => `<text x="${x + 18}" y="${y + 58 + k * 19}" font-size="14">${esc(l)}</text>`).join('\n')}
${dots}<text x="${x + tw - 18}" y="${y + th - 17}" font-size="12" text-anchor="end" class="muted">${s.done}/${s.total}</text>
</g>`;
  }).join('\n');

  const desc = js.map((j) => `${j.id}: ${journeyStatus(j, its).state}.`).join(' ');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t d">
<title id="t">BarkBot journeys</title>
<desc id="d">${c.done} of ${total} items done, ${c.partial} partial, ${c.open} open, ${c.unknown} not yet read on the oracle. ${esc(desc)}</desc>
${STYLE}
<rect class="bg" width="${W}" height="${H}" rx="16"/>
<text x="40" y="70" font-size="36" font-weight="700" letter-spacing="-0.8">Journeys</text>
<text x="40" y="102" font-size="19" class="muted">The spec of "works". Each passes when the oracle and BarkBot end the same way.</text>
<text x="1160" y="70" font-size="40" font-weight="700" text-anchor="end">${c.done}<tspan class="muted" font-weight="400"> / ${total}</tspan></text>
<text x="1160" y="102" font-size="16" text-anchor="end" class="muted">parity items done</text>
<rect x="40" y="124" width="1120" height="8" rx="4" class="track"/>${seg}
<text x="40" y="168" font-size="16"><tspan class="done">● done ${c.done}</tspan><tspan class="now" dx="24">● partial ${c.partial}</tspan><tspan class="todo" dx="24">● open ${c.open}</tspan><tspan class="unk" dx="24">● not yet read on the oracle ${c.unknown}</tspan></text>
<text x="1160" y="168" font-size="16" text-anchor="end" class="muted">one dot per item</text>
${tiles}
<text x="40" y="${H - 28}" font-size="14" class="muted">Generated by scripts/generate-parity.mjs from JOURNEYS.md and parity/items.json</text>
</svg>
`;
}

export function parityMd() {
  const its = items(), c = counts(its);
  const name = Object.fromEntries(slices().map((s) => [s.id, s.name]));
  const mark = { done: '✓ done', partial: '◐ partial', open: '○ open', unknown: '? unread' };
  const out = [
    '# Parity', '',
    '[![Journeys: one tile per journey, one dot per parity item](images/journeys.svg)](../JOURNEYS.md)', '',
    `${c.done} of ${its.length} items done, ${c.partial} partial, ${c.open} open, ${c.unknown} not yet read on the oracle.`,
    'Generated from [`parity/items.json`](../parity/items.json) by `npm run docs`. Edit the JSON, never this page.',
  ];
  for (const s of slices()) {
    const mine = its.filter((i) => i.slice === s.id);
    if (!mine.length) continue;
    out.push('', `## ${s.id} ${name[s.id]}`, '', '| Id | Item | Journey | Status | Gate or evidence |', '|---|---|---|---|---|');
    for (const i of mine) {
      const ev = [i.gate && `Gate: ${i.gate}`, i.evidence && `Evidence: ${i.evidence}`, ...(i.outOfScope || []).map((o) => `Out of scope: ${o}`)].filter(Boolean).join('. ');
      out.push(`| ${i.id} | ${i.title.replace(/\|/g, '\\|')} | ${i.journey || '—'} | ${mark[i.status]} | ${ev || '—'} |`);
    }
  }
  return out.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--stdout')) process.stdout.write(journeysSvg());
  else if (process.argv.includes('--md')) process.stdout.write(parityMd());
  else {
    writeFileSync(path('docs', 'images', 'journeys.svg'), journeysSvg());
    writeFileSync(path('docs', 'PARITY.md'), parityMd());
  }
}
